function getEmployers() {
    const users = JSON.parse(localStorage.getItem('awardsRecruitmentUsers')) || [];
    return users.filter(u => u.type === 'employer');
}

function saveEmployers(employers) {
    const users = JSON.parse(localStorage.getItem('awardsRecruitmentUsers')) || [];
    const nonEmployers = users.filter(u => u.type !== 'employer');
    const updated = [...nonEmployers, ...employers];
    localStorage.setItem('awardsRecruitmentUsers', JSON.stringify(updated));
}

function updateAdminStats() {
    const employers = getEmployers();
    const total = employers.length;
    const pending = employers.filter(e => e.status === 'pending' || !e.status).length;
    const approved = employers.filter(e => e.status === 'approved').length;
    const rejected = employers.filter(e => e.status === 'rejected').length;

    document.getElementById('totalEmployers').textContent = total;
    document.getElementById('pendingEmployers').textContent = pending;
    document.getElementById('approvedEmployers').textContent = approved;
    document.getElementById('rejectedEmployers').textContent = rejected;
}

let currentAdminTab = 'pending';

function renderAdminTable() {
    const tbody = document.getElementById('adminTableBody');
    if (!tbody) return;

    const employers = getEmployers();
    
    let filtered = employers;
    if (currentAdminTab === 'pending') {
        filtered = employers.filter(e => e.status === 'pending' || !e.status);
    } else if (currentAdminTab === 'approved') {
        filtered = employers.filter(e => e.status === 'approved');
    } else if (currentAdminTab === 'rejected') {
        filtered = employers.filter(e => e.status === 'rejected');
    }

    if (filtered.length === 0) {
        tbody.innerHTML = `
            <tr>
                <td colspan="5" class="no-data">
                    <i class="fas fa-users"></i>
                    <p>No ${currentAdminTab !== 'all' ? currentAdminTab : ''} employers found.</p>
                </td>
            </tr>
        `;
        return;
    }

    tbody.innerHTML = filtered.map(emp => `
        <tr>
            <td><strong>${emp.companyName || 'N/A'}</strong></td>
            <td>${emp.email}</td>
            <td>${emp.industry || 'N/A'}</td>
            <td>
                <span class="status-badge ${emp.status || 'pending'}">
                    ${emp.status || 'Pending'}
                </span>
            </td>
            <td class="actions">
                ${(emp.status === 'pending' || !emp.status) ? `
                    <button class="btn btn-success btn-sm" onclick="approveEmployer('${emp.email}')">
                        <i class="fas fa-check"></i> Approve
                    </button>
                    <button class="btn btn-danger btn-sm" onclick="rejectEmployer('${emp.email}')">
                        <i class="fas fa-times"></i> Reject
                    </button>
                ` : `
                    <button class="btn btn-outline-primary btn-sm" onclick="viewEmployer('${emp.email}')">
                        <i class="fas fa-eye"></i> View
                    </button>
                    ${emp.status === 'approved' ? `
                        <button class="btn btn-danger btn-sm" onclick="revokeEmployer('${emp.email}')">
                            <i class="fas fa-ban"></i> Revoke
                        </button>
                    ` : ''}
                `}
            </td>
        </tr>
    `).join('');
}

function switchTab(tab) {
    currentAdminTab = tab;
    document.querySelectorAll('.admin-tab').forEach(t => t.classList.remove('active'));
    document.querySelector(`.admin-tab[data-tab="${tab}"]`).classList.add('active');
    renderAdminTable();
}

function approveEmployer(email) {
    if (!confirm(`✅ Approve employer with email: ${email}? They will receive login credentials.`)) return;

    const employers = getEmployers();
    const index = employers.findIndex(e => e.email === email);
    
    if (index !== -1) {
        employers[index].status = 'approved';
        employers[index].approvedAt = new Date().toISOString();
        const tempPassword = generateTempPassword();
        employers[index].tempPassword = btoa(tempPassword);
        employers[index].tempPasswordPlain = tempPassword;
        
        saveEmployers(employers);
        updateAdminStats();
        renderAdminTable();
        
        alert(`✅ Employer Approved!\n\nCompany: ${employers[index].companyName}\nEmail: ${email}\nTemporary Password: ${tempPassword}\n\nShare these credentials with the employer. They can now login and post jobs.`);
    }
}

function rejectEmployer(email) {
    if (!confirm(`❌ Reject employer with email: ${email}?`)) return;

    const employers = getEmployers();
    const index = employers.findIndex(e => e.email === email);
    
    if (index !== -1) {
        employers[index].status = 'rejected';
        employers[index].rejectedAt = new Date().toISOString();
        saveEmployers(employers);
        updateAdminStats();
        renderAdminTable();
        alert('❌ Employer rejected.');
    }
}

function revokeEmployer(email) {
    if (!confirm(`⚠️ Revoke approval for employer with email: ${email}?`)) return;

    const employers = getEmployers();
    const index = employers.findIndex(e => e.email === email);
    
    if (index !== -1) {
        employers[index].status = 'pending';
        delete employers[index].tempPassword;
        delete employers[index].tempPasswordPlain;
        saveEmployers(employers);
        updateAdminStats();
        renderAdminTable();
        alert('⚠️ Employer approval revoked. They can no longer post jobs.');
    }
}

function viewEmployer(email) {
    const employers = getEmployers();
    const emp = employers.find(e => e.email === email);
    
    if (emp) {
        alert(`📋 Employer Details\n\nCompany: ${emp.companyName}\nEmail: ${emp.email}\nPhone: ${emp.phone}\nIndustry: ${emp.industry}\nLocation: ${emp.companyLocation}\nStatus: ${emp.status || 'Pending'}\n\nDescription: ${emp.companyDescription || 'N/A'}`);
    }
}

function generateTempPassword() {
    const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!@#$%';
    let password = '';
    for (let i = 0; i < 10; i++) {
        password += chars.charAt(Math.floor(Math.random() * chars.length));
    }
    return password;
}

