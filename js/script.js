function updateApplicationStatus(appId, status) {
    if (!confirm(`Update application status to "${status}"?`)) return;

    const applications = getApplications();
    const index = applications.findIndex(app => app.id === appId);

    if (index !== -1) {
        applications[index].status = status;
        applications[index].updatedAt = new Date().toISOString();
        saveApplications(applications);

        if (status === 'hired') {
            const jobId = applications[index].jobId;
            let allJobs = getAllJobs();
            const jobIndex = allJobs.findIndex(j => j.id === jobId);
            if (jobIndex !== -1) {
                const updatedJob = { ...allJobs[jobIndex] };
                updatedJob.hiredCount = (updatedJob.hiredCount || 0) + 1;
                
                let postedJobs = getJobs();
                const postedIndex = postedJobs.findIndex(j => j.id === jobId);
                if (postedIndex !== -1) {
                    postedJobs[postedIndex] = updatedJob;
                    saveJobs(postedJobs);
                }
            }
            
            alert(`🎉 Congratulations!\n\nYou have hired ${applications[index].applicantName} for ${applications[index].jobTitle}.\n\nAn email notification has been sent to the candidate.`);
        }

        loadEmployerApplications();
        alert(`✅ Application status updated to "${status}" successfully!`);
    }
}

function downloadDocument(applicantEmail, docType) {
    const applications = getApplications();
    const app = applications.find(a => a.applicantEmail === applicantEmail);

    if (!app) {
        alert('Application not found.');
        return;
    }

    let fileData = null;
    let fileName = '';
    let fileType = '';

    if (docType === 'cv') {
        fileData = app.cvFileData;
        fileName = app.cvFileName || 'CV.pdf';
        fileType = 'application/pdf';
    } else if (docType === 'cover') {
        fileData = app.coverFileData;
        fileName = app.coverFileName || 'Cover-Letter.pdf';
        fileType = 'application/pdf';
    } else if (docType === 'document') {
        fileData = app.documentFileData;
        fileName = app.documentFileName || 'Documents.pdf';
        fileType = 'application/pdf';
    }

    if (!fileData) {
        alert('No file data available for download.');
        return;
    }

    try {
        const byteCharacters = atob(fileData);
        const byteNumbers = new Array(byteCharacters.length);
        for (let i = 0; i < byteCharacters.length; i++) {
            byteNumbers[i] = byteCharacters.charCodeAt(i);
        }
        const byteArray = new Uint8Array(byteNumbers);
        const blob = new Blob([byteArray], { type: fileType });

        const link = document.createElement('a');
        link.href = URL.createObjectURL(blob);
        link.download = fileName;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);

        setTimeout(() => URL.revokeObjectURL(link.href), 100);

    } catch (error) {
        console.error('Error downloading file:', error);
        alert('Error downloading file. Please try again.');
    }
}

