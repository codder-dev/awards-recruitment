function getAllJobs() {
    const defaultJobs = Array.isArray(jobData) ? jobData : [];
    const postedJobs = (() => {
        try {
            return JSON.parse(localStorage.getItem('awardsRecruitmentJobs') || '[]');
        } catch (error) {
            return [];
        }
    })();

    const allJobs = [...defaultJobs, ...postedJobs];

    const uniqueJobs = allJobs.filter((job, index, self) =>
        index === self.findIndex(j => j.id === job.id)
    );

    return uniqueJobs;
}

