function handleLogin(e) {
    e.preventDefault();

    const email = document.getElementById('loginEmail').value.trim();
    const password = document.getElementById('loginPassword').value.trim();
    const rememberMe = document.getElementById('rememberMe')?.checked || false;
    const errorEl = document.getElementById('loginError');

    errorEl.classList.remove('show');
    document.querySelectorAll('.input-wrapper input').forEach(el => el.classList.remove('error', 'success'));

    if (!email || !password) {
        errorEl.innerHTML = '<i class="fas fa-exclamation-circle"></i> Please enter both email and password.';
        errorEl.classList.add('show');
        return;
    }

    const users = getUsers();
    const user = users.find(u => u.email === email);

    if (!user) {
        errorEl.innerHTML = '<i class="fas fa-exclamation-circle"></i> No account found with this email. Please create an account.';
        errorEl.classList.add('show');
        return;
    }

    if (user.type === 'employer') {
        errorEl.innerHTML = '<i class="fas fa-exclamation-circle"></i> This is a job seeker login page. Please use the <a href="employer-login.html">employer login</a>.';
        errorEl.classList.add('show');
        return;
    }

    const enteredPassword = btoa(password);
    const storedPassword = user.password || '';

    if (enteredPassword !== storedPassword) {
        errorEl.innerHTML = '<i class="fas fa-exclamation-circle"></i> Incorrect password. Please try again.';
        errorEl.classList.add('show');
        document.getElementById('loginPassword').classList.add('error');
        return;
    }

    if (rememberMe) {
        const rememberData = { email: email, password: password, savedAt: new Date().toISOString() };
        localStorage.setItem('awardsRecruitmentRememberMe', JSON.stringify(rememberData));
    } else {
        localStorage.removeItem('awardsRecruitmentRememberMe');
    }

    // Record the user's last login
user.lastLoginAt = new Date().toISOString();
user.lastActivityAt = new Date().toISOString();

saveUsers(users);

// Create the login session
localStorage.setItem('awardsRecruitmentCurrentUser', JSON.stringify({
    email: user.email,
    fullName: user.fullName || 'User',
    role: user.type || 'job-seeker',
    loggedIn: true
}));

window.location.href = 'jobseeker-dashboard.html';
}

