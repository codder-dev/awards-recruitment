// RENDER RELATED JOBS — On Job Detail Page
// ============================================================ */
function renderRelatedJobs(jobId) {
    const container = document.getElementById('relatedJobs');
    if (!container) return;

    if (!jobId) {
        container.innerHTML = `<p style="text-align:center;color:#6b7a8a;grid-column:1/-1;padding:20px;">No job selected.</p>`;
        return;
    }

    // Get all jobs
    const allJobs = getAllJobs();
    const currentJob = allJobs.find(j => j.id === jobId);

    if (!currentJob) {
        container.innerHTML = `<p style="text-align:center;color:#6b7a8a;grid-column:1/-1;padding:20px;">No related jobs found.</p>`;
        return;
    }

    // Find related jobs: same industry or experience level, exclude current job
    let related = allJobs
        .filter(j => j.id !== jobId && (j.industry === currentJob.industry || j.experience === currentJob.experience))
        .slice(0, 3);

    // If not enough related jobs, add some featured jobs
    if (related.length < 3) {
        const featured = allJobs
            .filter(j => j.id !== jobId && j.featured && !related.some(r => r.id === j.id))
            .slice(0, 3 - related.length);
        related = [...related, ...featured];
    }

    if (related.length === 0) {
        container.innerHTML = `<p style="text-align:center;color:#6b7a8a;grid-column:1/-1;padding:20px;">No related jobs found.</p>`;
        return;
    }

    container.innerHTML = related.map(job => `
        <div class="related-job-card">
            ${job.tag ? `<span class="related-job-tag">${job.tag}</span>` : ''}
            <h4>${job.title}</h4>
            <p class="company"><i class="fas fa-building"></i> ${job.company}</p>
            <p class="location"><i class="fas fa-map-marker-alt"></i> ${job.location}</p>
            <div class="related-job-meta">
                <span class="job-type ${job.type === 'Part Time' ? 'part-time' : 'full-time'}">${job.type}</span>
                <span class="job-salary">${job.salary}</span>
            </div>
            <a href="job-detail.html?id=${job.id}" class="btn btn-primary btn-sm">
                View Details
            </a>
        </div>
    `).join('');
}

