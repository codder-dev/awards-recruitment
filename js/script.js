// EDIT PROFILE — Load Data
// ============================================================ */
function loadEditProfile() {
    const session = JSON.parse(localStorage.getItem('awardsRecruitmentCurrentUser'));
    if (!session || !session.loggedIn) {
        window.location.href = 'login.html';
        return;
    }
    
    const users = JSON.parse(localStorage.getItem('awardsRecruitmentUsers')) || [];
    const user = users.find(u => u.email === session.email);
    
    if (!user) {
        window.location.href = 'jobseeker-dashboard.html';
        return;
    }
    
    // Fill form fields
    document.getElementById('editFullName').value = user.fullName || '';
    document.getElementById('editEmail').value = user.email || '';
    document.getElementById('editPhone').value = user.phone || '';
    document.getElementById('editLocation').value = user.location || '';
    document.getElementById('editIndustry').value = user.industry || '';
    document.getElementById('editExperience').value = user.experience || '';
    document.getElementById('editSkills').value = user.skills || '';
    
    // Load profile photo if exists
    if (user.profilePhoto) {
        document.getElementById('profilePhotoPreview').src = user.profilePhoto;
    } else {
        // Show placeholder with initials
        const initials = (user.fullName || 'User').split(' ').map(n => n[0]).join('').toUpperCase().slice(0, 2);
        const canvas = document.createElement('canvas');
        canvas.width = 120;
        canvas.height = 120;
        const ctx = canvas.getContext('2d');
        ctx.fillStyle = '#f47a20';
        ctx.beginPath();
        ctx.arc(60, 60, 60, 0, Math.PI * 2);
        ctx.fill();
        ctx.fillStyle = '#fff';
        ctx.font = 'bold 40px Inter, sans-serif';
        ctx.textAlign = 'center';
        ctx.textBaseline = 'middle';
        ctx.fillText(initials, 60, 62);
        document.getElementById('profilePhotoPreview').src = canvas.toDataURL();
    }
}

