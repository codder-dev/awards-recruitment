let currentStep = 1;
const totalSteps = 3;

function nextStep() {
    if (validateStep(currentStep)) {
        document.getElementById(`step${currentStep}`).classList.remove('active');
        document.querySelectorAll('.form-progress-step')[currentStep - 1].classList.remove('active');
        document.querySelectorAll('.form-progress-step')[currentStep - 1].classList.add('completed');
        
        currentStep++;
        document.getElementById(`step${currentStep}`).classList.add('active');
        document.querySelectorAll('.form-progress-step')[currentStep - 1].classList.add('active');
        updateProgressLine();
    }
}

function prevStep() {
    if (currentStep > 1) {
        document.getElementById(`step${currentStep}`).classList.remove('active');
        document.querySelectorAll('.form-progress-step')[currentStep - 1].classList.remove('active');
        
        currentStep--;
        document.getElementById(`step${currentStep}`).classList.add('active');
        document.querySelectorAll('.form-progress-step')[currentStep - 1].classList.add('active');
        document.querySelectorAll('.form-progress-step')[currentStep - 1].classList.remove('completed');
        updateProgressLine();
    }
}

function updateProgressLine() {
    const steps = document.querySelectorAll('.form-progress-step');
    steps.forEach((step, index) => {
        if (index < currentStep) {
            step.classList.add('active');
        } else {
            step.classList.remove('active');
        }
    });
}

function validateStep(step) {
    let valid = true;
    
    document.querySelectorAll('.form-error').forEach(el => el.classList.remove('show'));
    document.querySelectorAll('.input-wrapper').forEach(el => el.classList.remove('error', 'success'));
    
    if (step === 1) {
        const fullName = document.getElementById('fullName');
        if (!fullName.value.trim()) {
            showError('fullNameWrapper', 'fullNameError');
            valid = false;
        } else {
            document.getElementById('fullNameWrapper').classList.add('success');
        }
        
        const email = document.getElementById('email');
        const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
        if (!email.value.trim() || !emailPattern.test(email.value)) {
            showError('emailWrapper', 'emailError');
            valid = false;
        } else {
            document.getElementById('emailWrapper').classList.add('success');
        }
        
        const phone = document.getElementById('phone');
        if (!phone.value.trim() || phone.value.length < 10) {
            showError('phoneWrapper', 'phoneError');
            valid = false;
        } else {
            document.getElementById('phoneWrapper').classList.add('success');
        }
        
        const location = document.getElementById('location');
        if (!location.value.trim()) {
            showError('locationWrapper', 'locationError');
            valid = false;
        } else {
            document.getElementById('locationWrapper').classList.add('success');
        }
    }
    
    if (step === 2) {
        const industry = document.getElementById('industry');
        if (!industry.value) {
            showError('industryWrapper', 'industryError');
            valid = false;
        } else {
            document.getElementById('industryWrapper').classList.add('success');
        }
        
        const experience = document.getElementById('experience');
        if (!experience.value) {
            showError('experienceWrapper', 'experienceError');
            valid = false;
        } else {
            document.getElementById('experienceWrapper').classList.add('success');
        }
        const education = document.getElementById('education');
        if (!education.value){
            showError('educationWrapper', 'educationError');
            valid = false;
        }else {
            document.getElementById('educationWrapper').classList.add('success');
        }
        
        const cvInput = document.getElementById('cvFileInput');
        if (!cvInput.files || cvInput.files.length === 0) {
            document.getElementById('cvError').classList.add('show');
            valid = false;
        } else {
            document.getElementById('cvError').classList.remove('show');
        }
    }
    
    if (step === 3) {
        const password = document.getElementById('password');
        if (!checkPasswordStrength(password.value)) {
            document.getElementById('passwordError').classList.add('show');
            document.getElementById('passwordWrapper').classList.add('error');
            valid = false;
        } else {
            document.getElementById('passwordError').classList.remove('show');
            document.getElementById('passwordWrapper').classList.add('success');
        }
        
        const confirmPassword = document.getElementById('confirmPassword');
        if (confirmPassword.value !== document.getElementById('password').value || !confirmPassword.value) {
            document.getElementById('confirmError').classList.add('show');
            document.getElementById('confirmWrapper').classList.add('error');
            valid = false;
        } else {
            document.getElementById('confirmError').classList.remove('show');
            document.getElementById('confirmWrapper').classList.add('success');
        }
        
        const role = document.getElementById('role');
        if (!role.value) {
            showError('roleWrapper', 'roleError');
            valid = false;
        } else {
            document.getElementById('roleWrapper').classList.add('success');
        }
        
        const terms = document.getElementById('terms');
        if (!terms.checked) {
            document.getElementById('termsError').classList.add('show');
            valid = false;
        } else {
            document.getElementById('termsError').classList.remove('show');
        }
    }
    
    if (!valid) {
        const firstError = document.querySelector('.form-error.show');
        if (firstError) {
            firstError.scrollIntoView({ behavior: 'smooth', block: 'center' });
        }
    }
    
    return valid;
}

function handleRegistration(e) {
    e.preventDefault();
    
    if (!validateStep(3)) return;
    
    const userData = {
        fullName: document.getElementById('fullName').value.trim(),
        email: document.getElementById('email').value.trim(),
        phone: document.getElementById('phone').value.trim(),
        location: document.getElementById('location').value.trim(),
        dob: document.getElementById('dob').value,
        industry: document.getElementById('industry').value,
        education: document.getElementById('education').value,
        experience: document.getElementById('experience').value,
        skills: document.getElementById('skills').value.trim(),
        role: document.getElementById('role').value,
        newsletter: document.getElementById('newsletter').checked,
        createdAt: new Date().toISOString()
    };
    
    const password = document.getElementById('password').value;
    userData.password = btoa(password);
    
    const cvFile = document.getElementById('cvFileInput').files[0];
    if (cvFile) {
        userData.cvFileName = cvFile.name;
        userData.cvFileSize = cvFile.size;
        userData.cvFileType = cvFile.type;
    }
    
    const coverFile = document.getElementById('coverFileInput').files[0];
    if (coverFile) {
        userData.coverFileName = coverFile.name;
        userData.coverFileSize = coverFile.size;
        userData.coverFileType = coverFile.type;
    }
    
    try {
        let users = JSON.parse(localStorage.getItem('awardsRecruitmentUsers')) || [];
        
        if (users.some(u => u.email === userData.email)) {
            alert('An account with this email already exists. Please sign in or use a different email.');
            return;
        }
        
        users.push(userData);
        localStorage.setItem('awardsRecruitmentUsers', JSON.stringify(users));
        
        localStorage.setItem('awardsRecruitmentCurrentUser', JSON.stringify({
            email: userData.email,
            fullName: userData.fullName,
            role: userData.role,
            loggedIn: true
        }));
        
        document.getElementById('successModal').classList.add('show');
        
        setTimeout(() => {
            document.getElementById('registrationForm').reset();
            document.querySelectorAll('.form-progress-step').forEach(step => {
                step.classList.remove('active', 'completed');
            });
            document.querySelector('.form-progress-step').classList.add('active');
            currentStep = 1;
            document.getElementById('step1').classList.add('active');
            document.getElementById('step2').classList.remove('active');
            document.getElementById('step3').classList.remove('active');
            document.getElementById('cvUploadArea').classList.remove('has-file');
            document.getElementById('coverLetterArea').classList.remove('has-file');
            document.querySelectorAll('.input-wrapper').forEach(el => el.classList.remove('error', 'success'));
            document.querySelectorAll('.form-error').forEach(el => el.classList.remove('show'));
            document.querySelectorAll('.password-requirements .req-item').forEach(el => {
                el.classList.remove('met', 'failed');
                el.querySelector('i').className = 'fas fa-circle';
            });
            document.getElementById('cvFileName').textContent = 'document.pdf';
            document.getElementById('coverFileName').textContent = 'cover-letter.pdf';
            updateProgressLine();
        }, 3000);
        
    } catch (error) {
        console.error('Error saving user data:', error);
        alert('There was an error creating your account. Please try again.');
    }
}

