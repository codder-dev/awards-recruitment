function revokeEmployer(email) {
    if (!confirm(`⚠️ Revoke approval for employer with email: ${email}?`)) return;

    const employers = getEmployers();
    const index = employers.findIndex(e => e.email === email);

    if (index !== -1) {
        employers[index].status = 'pending';
        delete employers[index].tempPassword;
        delete employers[index].tempPasswordPlain;
        saveEmployers(employers);
        updateAdminStats();
        renderAdminTables();
        alert('⚠️ Employer approval revoked.');
    }
}

