function calculateProfileCompletion(user) {

    if (!user) return 0;

    const fields = [
        'phone',
        'location',
        'education',
        'fieldOfStudy',
        'industry',
        'experience',
        'skills',
        'bio',
        'cvFileName',
        'coverFileName'
    ];

    const completed = fields.filter(field => {
        return user[field] &&
               String(user[field]).trim() !== '';
    }).length;

    return Math.round((completed / fields.length) * 100);
}

