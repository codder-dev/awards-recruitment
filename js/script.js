// HANDLE APPLICATION SUBMISSION
// ============================================================ */
function handleApply(e) {
    e.preventDefault();
    
    let valid = true;
    
    // Clear previous errors
    document.querySelectorAll('.form-error').forEach(el => el.classList.remove('show'));
    document.querySelectorAll('.input-wrapper').forEach(el => el.classList.remove('error', 'success'));
    document.getElementById('cvFileError').classList.remove('show');
    document.getElementById('cvFileTypeError').style.display = 'none';
    document.getElementById('coverFileError').classList.remove('show');
    document.getElementById('coverFileTypeError').style.display = 'none';
    document.getElementById('documentFileError').classList.remove('show');
    document.getElementById('documentFileTypeError').style.display = 'none';
    
    // Validate Name
    const name = document.getElementById('applicantName');
    if (!name.value.trim()) {
        document.getElementById('nameWrapper').classList.add('error');
        document.getElementById('nameError').classList.add('show');
        valid = false;
    } else {
        document.getElementById('nameWrapper').classList.add('success');
    }
    
    // Validate Email
    const email = document.getElementById('applicantEmail');
    const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!email.value.trim() || !emailPattern.test(email.value)) {
        document.getElementById('emailWrapper').classList.add('error');
        document.getElementById('emailError').classList.add('show');
        valid = false;
    } else {
        document.getElementById('emailWrapper').classList.add('success');
    }
    
    // Validate Phone
    const phone = document.getElementById('applicantPhone');
    if (!phone.value.trim() || phone.value.length < 10) {
        document.getElementById('phoneWrapper').classList.add('error');
        document.getElementById('phoneError').classList.add('show');
        valid = false;
    } else {
        document.getElementById('phoneWrapper').classList.add('success');
    }
    
    // Validate CV
    const cvInput = document.getElementById('cvFileInput');
    if (!cvInput.files || cvInput.files.length === 0) {
        document.getElementById('cvFileError').classList.add('show');
        valid = false;
    } else {
        const file = cvInput.files[0];
        if (file.type !== 'application/pdf') {
            document.getElementById('cvFileTypeError').style.display = 'block';
            valid = false;
        }
    }
    
    // Validate Cover Letter
    const coverInput = document.getElementById('coverFileInput');
    if (!coverInput.files || coverInput.files.length === 0) {
        document.getElementById('coverFileError').classList.add('show');
        valid = false;
    } else {
        const file = coverInput.files[0];
        if (file.type !== 'application/pdf') {
            document.getElementById('coverFileTypeError').style.display = 'block';
            valid = false;
        }
    }
    //validate documents
    const documentInput = document.getElementById('documentFileInput');
    if (!documentInput.files || documentInput.files.length === 0) {
        document.getElementById('documentFileError').classList.add('show');
        valid = false;
    }else{
        const file = documentInput.files[0];
        if (file.type !== 'application/pdf') {
            document.getElementById('documentFileTypeError').style.display = 'block';
            valid = false;
        }
    }
    
    // Validate Terms
    const terms = document.getElementById('applyTerms');
    if (!terms.checked) {
        document.getElementById('termsError').classList.add('show');
        valid = false;
    } else {
        document.getElementById('termsError').classList.remove('show');
    }
    
    if (!valid) {
        const firstError = document.querySelector('.form-error.show, .file-error.show');
        if (firstError) {
            firstError.scrollIntoView({ behavior: 'smooth', block: 'center' });
        }
        return;
    }
    
     // Get job ID
    const jobId = parseInt(document.getElementById('applyForm').dataset.jobId);
    
    // Helper function to convert file to base64
    function fileToBase64(file) {
        return new Promise((resolve, reject) => {
            const reader = new FileReader();
            reader.onload = () => {
                // Remove data URL prefix to get just base64
                const base64 = reader.result.split(',')[1];
                resolve(base64);
            };
            reader.onerror = reject;
            reader.readAsDataURL(file);
        });
    }
    
    // Process files asynchronously
    async function processApplication() {
        try {
            const cvFile = cvInput.files[0];
            const coverFile = coverInput.files[0];
            const documentFile = documentInput.files[0];
            
            // Convert files to base64
            const cvBase64 = await fileToBase64(cvFile);
            const coverBase64 = await fileToBase64(coverFile);
            const documentBase64 = await fileToBase64(documentFile);
            
            // Create application data with file contents
            const applicationData = {
                id: Date.now(),
                jobId: jobId,
                jobTitle: document.getElementById('jobTitleDisplay').textContent,
                jobCompany: document.getElementById('jobCompanyDisplay').textContent,
                applicantName: name.value.trim(),
                applicantEmail: email.value.trim(),
                applicantPhone: phone.value.trim(),
                cvFileName: cvFile.name,
                cvFileData: cvBase64,
                coverFileName: coverFile.name,
                coverFileData: coverBase64,
                documentFileName: documentFile.name,
                documentFileData: documentBase64,
                appliedAt: new Date().toISOString(),
                status: 'pending'
            };
            
            // Save to localStorage
            let applications = JSON.parse(localStorage.getItem('awardsRecruitmentApplications')) || [];
            applications.push(applicationData);
            localStorage.setItem('awardsRecruitmentApplications', JSON.stringify(applications));
            
            // Update job applicants count
            updateJobApplicants(jobId);
            
            // Show success modal
            document.getElementById('successModal').classList.add('show');
            
            // Reset form after delay
            setTimeout(() => {
                document.getElementById('applyForm').reset();
                document.getElementById('cvUploadArea').classList.remove('has-file');
                document.getElementById('coverUploadArea').classList.remove('has-file');
                document.getElementById('documentUploadArea').classList.remove('has-file');
                document.getElementById('cvFileName').textContent = 'document.pdf';
                document.getElementById('coverFileName').textContent = 'cover-letter.pdf';
                document.getElementById('documentFileName').textContent = 'Documents.pdf';
                document.querySelectorAll('.input-wrapper').forEach(el => el.classList.remove('error', 'success'));
                document.querySelectorAll('.form-error').forEach(el => el.classList.remove('show'));
                document.querySelectorAll('.file-error').forEach(el => el.classList.remove('show'));
                document.getElementById('cvFileTypeError').style.display = 'none';
                document.getElementById('coverFileTypeError').style.display = 'none';
                document.getElementById('documentFileTypeError').style.display = 'none';
            }, 3000);
            
        } catch (error) {
            console.error('Error processing files:', error);
            alert('There was an error processing your files. Please try again.');
        }
    }
    
    processApplication();
}

