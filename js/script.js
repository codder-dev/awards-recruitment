// OBSERVER FOR STATS — Triggers animation when visible
// ============================================================ */
function initStatsAnimation() {
    // Find all stat sections
    const statSections = document.querySelectorAll('.stats, .page-stats, .about-stats, .careers-stats, .partner-stats, .service-stats');
    
    statSections.forEach(section => {
        // Check if stats are already visible
        const rect = section.getBoundingClientRect();
        const isVisible = rect.top < window.innerHeight && rect.bottom > 0;
        
        if (isVisible) {
            animateStats();
        } else {
            // Use IntersectionObserver for scroll-triggered animation
            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        animateStats();
                        observer.unobserve(entry.target);
                    }
                });
            }, { threshold: 0.3 });
            
            observer.observe(section);
        }
    });
}

