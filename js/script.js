function animateStats() {
    const statItems = document.querySelectorAll('.stat-item, .page-stat-item, .about-stat-item, .careers-stat-item, .partner-stat-item, .service-stat-item');

    statItems.forEach(stat => {
        const numberEl = stat.querySelector('.stat-number, .page-stat-number, .about-stat-number, .careers-stat-number, .partner-stat-number, .service-stat-number');
        if (!numberEl) return;
        if (numberEl.dataset.animated === 'true') return;

        let target = parseInt(numberEl.getAttribute('data-target'));
        if (!target && numberEl.textContent) {
            const text = numberEl.textContent.replace(/[^0-9]/g, '');
            target = parseInt(text) || 0;
        }
        if (!target || target <= 0) return;

        const duration = 1800;
        const frameCount = Math.ceil(duration / 16);
        const step = target / frameCount;
        let current = 0;
        let frameIndex = 0;

        const updateCounter = () => {
            frameIndex++;
            current = frameIndex * step;
            if (frameIndex >= frameCount) {
                numberEl.textContent = target + (target > 100 ? '+' : '');
                numberEl.dataset.animated = 'true';
                return;
            }
            numberEl.textContent = Math.floor(current);
            requestAnimationFrame(updateCounter);
        };

        numberEl.textContent = '0';
        numberEl.dataset.animated = 'false';
        updateCounter();
    });
}

function initStatsAnimation() {
    const statSections = document.querySelectorAll('.stats, .page-stats, .about-stats, .careers-stats, .partner-stats, .service-stats');
    statSections.forEach(section => {
        const rect = section.getBoundingClientRect();
        const isVisible = rect.top < window.innerHeight && rect.bottom > 0;
        if (isVisible) {
            animateStats();
        } else {
            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        animateStats();
                        observer.unobserve(entry.target);
                    }
                });
            }, { threshold: 0.3 });
            observer.observe(section);
        }
    });
}

