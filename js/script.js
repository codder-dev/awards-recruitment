// FILTER JOBS (Careers Page)
// ============================================================ */
let currentFilter = 'all';
let currentJobs = [];

function filterJobs() {
    const search = document.getElementById('jobSearchInput')?.value?.toLowerCase() || '';
    const sort = document.getElementById('sortOrder')?.value || 'latest';

    let filtered = getAllJobs();

    if (currentFilter === 'featured') {
        filtered = filtered.filter(j => j.featured);
    } else if (currentFilter === 'full-time') {
        filtered = filtered.filter(j => j.type === 'Full Time');
    } else if (currentFilter === 'part-time') {
        filtered = filtered.filter(j => j.type === 'Part Time');
    } else if (currentFilter === 'remote') {
        filtered = filtered.filter(j => j.type === 'Remote');
    } else if (currentFilter === 'internship') {
        filtered = filtered.filter(j => j.type === 'Internship');
    }

    if (search) {
        filtered = filtered.filter(job =>
            job.title.toLowerCase().includes(search) ||
            job.company.toLowerCase().includes(search) ||
            job.location.toLowerCase().includes(search) ||
            job.industry.toLowerCase().includes(search)
        );
    }

    if (sort === 'featured') {
        filtered = filtered.sort((a, b) => (b.featured ? 1 : 0) - (a.featured ? 1 : 0));
    } else if (sort === 'salary-high') {
        filtered = filtered.sort((a, b) => {
            const aSal = parseInt(a.salary.replace(/[^0-9]/g, ''));
            const bSal = parseInt(b.salary.replace(/[^0-9]/g, ''));
            return bSal - aSal;
        });
    } else if (sort === 'salary-low') {
        filtered = filtered.sort((a, b) => {
            const aSal = parseInt(a.salary.replace(/[^0-9]/g, ''));
            const bSal = parseInt(b.salary.replace(/[^0-9]/g, ''));
            return aSal - bSal;
        });
    }

    currentJobs = filtered;
    renderJobsList(filtered);
    updateCareersStats(filtered);
}

function filterByTab(filter) {
    currentFilter = filter;
    document.querySelectorAll('.filter-tab').forEach(tab => {
        tab.classList.remove('active');
        if (tab.dataset.filter === filter) {
            tab.classList.add('active');
        }
    });
    filterJobs();
}

function resetFilters() {
    const searchInput = document.getElementById('jobSearchInput');
    const sortSelect = document.getElementById('sortOrder');
    
    if (searchInput) searchInput.value = '';
    if (sortSelect) sortSelect.value = 'latest';
    
    currentFilter = 'all';
    document.querySelectorAll('.filter-tab').forEach(tab => {
        tab.classList.remove('active');
        if (tab.dataset.filter === 'all') {
            tab.classList.add('active');
        }
    });
    filterJobs();
}

function initCareersPage() {
    if (document.getElementById('jobsList')) {
        const allJobs = getAllJobs();
        currentJobs = allJobs;
        renderJobsList(allJobs);
        updateCareersStats(allJobs);
        animateStats();
    }
}

