function handleEmployerLogin(e) {
    e.preventDefault();
    
    const email = document.getElementById('loginEmail').value.trim();
    const password = document.getElementById('loginPassword').value.trim();
    const errorEl = document.getElementById('loginError');
    
    errorEl.classList.remove('show');
    document.querySelectorAll('.input-wrapper input').forEach(el => el.classList.remove('error', 'success'));
    
    if (!email || !password) {
        errorEl.innerHTML = '<i class="fas fa-exclamation-circle"></i> Please enter both email and password.';
        errorEl.classList.add('show');
        return;
    }
    
    const users = JSON.parse(localStorage.getItem('awardsRecruitmentUsers')) || [];
    
    const employer = users.find(u => 
        u.type === 'employer' && 
        u.email === email && 
        u.status === 'approved'
    );
    
    if (!employer) {
        errorEl.innerHTML = '<i class="fas fa-exclamation-circle"></i> Account not found or not approved. Please register and wait for approval.';
        errorEl.classList.add('show');
        return;
    }
    
    const enteredPassword = btoa(password);
    const storedPassword = employer.tempPassword || employer.password;
    
    if (enteredPassword !== storedPassword) {
        errorEl.innerHTML = '<i class="fas fa-exclamation-circle"></i> Incorrect password. Please try again.';
        errorEl.classList.add('show');
        return;
    }
    
    const successOverlay = document.getElementById('successOverlay');
    const welcomeMessage = document.getElementById('welcomeMessage');
    const welcomeSubtext = document.getElementById('welcomeSubtext');
    
    welcomeMessage.textContent = `Welcome back, ${employer.companyName}!`;
    welcomeSubtext.textContent = 'Redirecting you to the dashboard...';
    successOverlay.classList.add('show');
    
    localStorage.setItem('employerSession', JSON.stringify({
        email: employer.email,
        companyName: employer.companyName,
        loggedIn: true
    }));
    
    setTimeout(() => {
        window.location.href = 'post-job.html';
    }, 3000);
}

