function updateCareersStats(jobs) {
    const total = jobs.length;
    const featured = jobs.filter(j => j.featured).length;
    const categories = new Set(jobs.map(j => j.industry));
    const companies = new Set(jobs.map(j => j.company));

    const totalJobsStat = document.getElementById('totalJobsStat');
    const featuredJobsStat = document.getElementById('featuredJobsStat');
    const categoriesStat = document.getElementById('categoriesStat');
    const companiesStat = document.getElementById('companiesStat');
    const totalJobsCount = document.getElementById('totalJobsCount');
    const jobsFoundText = document.getElementById('jobsFoundText');

    const setStat = (el, value) => {
        if (!el) return;
        el.dataset.target = value;
        el.setAttribute('data-target', value);
        el.dataset.animated = 'false';
        el.textContent = '0';
    };

    setStat(totalJobsStat, total);
    setStat(featuredJobsStat, featured);
    setStat(categoriesStat, categories.size);
    setStat(companiesStat, companies.size);

    if (totalJobsCount) totalJobsCount.textContent = total + ' Jobs Available';
    if (jobsFoundText) jobsFoundText.textContent = `Found ${total} job${total > 1 ? 's' : ''} for you`;

    animateStats();
}
