// RENDER SAVED JOBS
// ============================================================ */
function renderSavedJobs(savedJobs) {
    const container = document.getElementById('savedJobsList');
    
    if (savedJobs.length === 0) {
        container.innerHTML = `
            <div class="no-saved">
                <i class="fas fa-bookmark"></i>
                <p>No saved jobs yet</p>
                <a href="careers.html" class="btn btn-outline-primary btn-sm" style="margin-top:5px;">
                    <i class="fas fa-search"></i> Find Jobs
                </a>
            </div>
        `;
        return;
    }
    
    container.innerHTML = savedJobs.map(item => `
        <div class="saved-job-item">
            <div class="job-title">
                ${item.jobTitle || 'Position'}
                <small>${item.jobCompany || 'Company'} • ${item.location || ''}</small>
            </div>
            <div class="saved-actions">
                <a href="job-detail.html?id=${item.jobId}" class="btn btn-primary btn-sm">
                    <i class="fas fa-eye"></i> View
                </a>
                <button class="btn btn-outline-danger btn-sm" onclick="removeSavedJob(${item.jobId})">
                    <i class="fas fa-times"></i>
                </button>
            </div>
        </div>
    `).join('');
}

