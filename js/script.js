// ============================================================ */
// HANDLE UPDATE PROFILE — With Page Reload
// ============================================================ */
function handleUpdateProfile(e) {
    e.preventDefault();
    
    let valid = true;
    
    // Clear previous errors
    document.querySelectorAll('.form-error').forEach(el => el.classList.remove('show'));
    document.querySelectorAll('.input-wrapper').forEach(el => el.classList.remove('error', 'success'));
    document.getElementById('updateSuccess').classList.remove('show');
    
    // Get values
    const fullName = document.getElementById('editFullName').value.trim();
    const phone = document.getElementById('editPhone').value.trim();
    const location = document.getElementById('editLocation').value.trim();
    const industry = document.getElementById('editIndustry').value;
    const experience = document.getElementById('editExperience').value;
    const skills = document.getElementById('editSkills').value.trim();
    const profilePhoto = document.getElementById('profilePhotoPreview').src;
    
    // Validate Name
    if (!fullName) {
        document.getElementById('nameWrapper').classList.add('error');
        document.getElementById('nameError').classList.add('show');
        valid = false;
    } else {
        document.getElementById('nameWrapper').classList.add('success');
    }
    
    // Validate Phone
    if (!phone || phone.length < 10) {
        document.getElementById('phoneWrapper').classList.add('error');
        document.getElementById('phoneError').classList.add('show');
        valid = false;
    } else {
        document.getElementById('phoneWrapper').classList.add('success');
    }
    
    // Validate Location
    if (!location) {
        document.getElementById('locationWrapper').classList.add('error');
        document.getElementById('locationError').classList.add('show');
        valid = false;
    } else {
        document.getElementById('locationWrapper').classList.add('success');
    }
    
    // Validate Industry
    if (!industry) {
        document.getElementById('industryWrapper').classList.add('error');
        document.getElementById('industryError').classList.add('show');
        valid = false;
    } else {
        document.getElementById('industryWrapper').classList.add('success');
    }
    
    // Validate Experience
    if (!experience) {
        document.getElementById('experienceWrapper').classList.add('error');
        document.getElementById('experienceError').classList.add('show');
        valid = false;
    } else {
        document.getElementById('experienceWrapper').classList.add('success');
    }
    
    if (!valid) {
        const firstError = document.querySelector('.form-error.show');
        if (firstError) {
            firstError.scrollIntoView({ behavior: 'smooth', block: 'center' });
        }
        return;
    }
    
    // Get current user session
    const session = JSON.parse(localStorage.getItem('awardsRecruitmentCurrentUser'));
    if (!session) {
        window.location.href = 'login.html';
        return;
    }
    
    // Update user data
    const users = JSON.parse(localStorage.getItem('awardsRecruitmentUsers')) || [];
    const userIndex = users.findIndex(u => u.email === session.email);
    
    if (userIndex !== -1) {
        // Update fields
        users[userIndex].fullName = fullName;
        users[userIndex].phone = phone;
        users[userIndex].location = location;
        users[userIndex].industry = industry;
        users[userIndex].experience = experience;
        users[userIndex].skills = skills;
        
        // Update profile photo if changed
        if (profilePhoto && profilePhoto !== users[userIndex].profilePhoto) {
            users[userIndex].profilePhoto = profilePhoto;
        }
        
        localStorage.setItem('awardsRecruitmentUsers', JSON.stringify(users));
        
        // Update session
        session.fullName = fullName;
        localStorage.setItem('awardsRecruitmentCurrentUser', JSON.stringify(session));
        
        // Show success message
        const successMsg = document.getElementById('successMessage');
        successMsg.textContent = 'Profile updated successfully! Reloading...';
        document.getElementById('updateSuccess').classList.add('show');
        
        // Redirect back to the dashboard after saving
        setTimeout(() => {
            window.location.href = 'jobseeker-dashboard.html';
        }, 1500);
    }
}